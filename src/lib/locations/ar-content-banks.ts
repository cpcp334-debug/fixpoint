export function pick<T>(arr: T[], h: number, salt = 0): T {
  return arr[Math.abs(h + salt) % arr.length]!;
}

export function hashStr(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
